// Quick lookup helper for Shlokas by Chapter & Shloka number
export function findGitaShloka(chapter: number, shloka: number): GitaShloka | undefined {
  return FAMOUS_GITA_SHLOKAS.find((s) => s.chapter === chapter && s.shloka === shloka);
}

// Quick lookup helper for Purana by name/keyword
export function findPuranaByName(query: string): PuranaInfo | undefined {
  const clean = query.toLowerCase().trim();
  return EIGHTEEN_MAHAPURANAS.find(
    (p) =>
      p.id.includes(clean) ||
      p.name.toLowerCase().includes(clean) ||
      p.sanskritName.includes(clean) ||
      p.keyThemes.some((t) => t.toLowerCase().includes(clean))
  );
}
